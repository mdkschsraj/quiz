import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import QRCode from "qrcode";
import { db } from "@/lib/supabase";
import { requireAdmin } from "@/lib/admin";
import { centerLink } from "@/lib/site";

function slugify(s: string): string {
  return s.toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60);
}

async function addCenter(formData: FormData) {
  "use server";
  await requireAdmin();
  const name = String(formData.get("name") ?? "").trim();
  const slug = slugify(String(formData.get("slug") ?? "") || name);
  if (!name || !slug) redirect("/admin/centers?msg=" + encodeURIComponent("Enter a center name."));
  const { error } = await db().from("centers").insert({ name, slug });
  if (error) redirect("/admin/centers?msg=" + encodeURIComponent(error.code === "23505" ? "That link name is already used." : "Could not add center."));
  revalidatePath("/admin/centers");
  redirect("/admin/centers?msg=" + encodeURIComponent("Center created. Its unique QR code is below."));
}

async function toggleCenter(formData: FormData) {
  "use server";
  await requireAdmin();
  const id = String(formData.get("id") ?? "");
  const active = formData.get("active") === "true";
  await db().from("centers").update({ active: !active }).eq("id", id);
  revalidatePath("/admin/centers");
}

type Center = { id: string; name: string; slug: string; active: boolean };
type Stats = { center_id: string; scans: number; unique_scanners: number; students_started: number; students_finished: number };

export default async function CentersPage({ searchParams }: { searchParams: Promise<{ msg?: string }> }) {
  await requireAdmin();
  const { msg } = await searchParams;

  const [{ data: centerRows }, { data: statRows, error: statsError }] = await Promise.all([
    db().from("centers").select("id, name, slug, active").order("created_at", { ascending: false }),
    db().rpc("center_stats"),
  ]);
  const centers = (centerRows ?? []) as Center[];
  const stats = new Map(((statRows ?? []) as Stats[]).map((s) => [s.center_id, s]));

  const cards = await Promise.all(
    centers.map(async (c) => {
      const link = centerLink(c.slug);
      const svg = link
        ? await QRCode.toString(link, { type: "svg", margin: 1, width: 150, errorCorrectionLevel: "M" })
        : null;
      return { c, link, svg, s: stats.get(c.id) };
    })
  );

  return (
    <>
      <h1>Coaching centers and QR codes</h1>
      {msg && <div className="notice" role="status">{msg}</div>}
      {!centerLink("x") && (
        <div className="notice" role="alert">
          NEXT_PUBLIC_SITE_URL is not set, so QR codes cannot be generated. Set it to your live site address (for example https://yourapp.vercel.app) and redeploy.
        </div>
      )}
      {statsError && (
        <div className="notice" role="alert">
          Scan statistics are unavailable. Run supabase/migrations/002_scans.sql in the Supabase SQL editor.
        </div>
      )}

      <div className="card">
        <h2>Create a center and its QR code</h2>
        <form action={addCenter} className="row">
          <div><label htmlFor="name">Center name</label><input id="name" name="name" type="text" required /></div>
          <div><label htmlFor="slug">Link name (optional)</label><input id="slug" name="slug" type="text" placeholder="auto from name" /></div>
          <div style={{ flex: "0 0 auto" }}><button className="smallbtn" type="submit">Create</button></div>
        </form>
        <p className="muted" style={{ marginTop: 10 }}>
          Each center gets its own link and QR code. Do not change a center&apos;s link name after its QR code is printed.
        </p>
      </div>

      {cards.length === 0 && <div className="card">No centers yet.</div>}
      {cards.map(({ c, link, svg, s }) => (
        <div className="card" key={c.id}>
          <div className="row" style={{ alignItems: "center" }}>
            <div style={{ flex: "0 0 160px" }}>
              {svg ? (
                // Generated by the qrcode library from our own link; safe to inline.
                <div style={{ background: "#fff", padding: 4, borderRadius: 8, width: 158 }} dangerouslySetInnerHTML={{ __html: svg }} />
              ) : (
                <div className="readonly muted">No QR yet</div>
              )}
            </div>
            <div style={{ flex: "2 1 260px" }}>
              <h2 style={{ marginBottom: 4 }}>
                {c.name} {c.active ? <span className="badge ok">Active</span> : <span className="badge warn">Paused</span>}
              </h2>
              <div className="muted" style={{ wordBreak: "break-all" }}>{link ?? `/c/${c.slug}`}</div>
              <div style={{ display: "flex", gap: 8, marginTop: 10, flexWrap: "wrap" }}>
                {link && <a className="smallbtn" href={`/admin/centers/${c.slug}/qr?format=png`}>Download PNG</a>}
                {link && <a className="smallbtn" href={`/admin/centers/${c.slug}/qr?format=svg`}>Download SVG</a>}
                <form action={toggleCenter}>
                  <input type="hidden" name="id" value={c.id} />
                  <input type="hidden" name="active" value={String(c.active)} />
                  <button className="smallbtn" type="submit">{c.active ? "Pause" : "Activate"}</button>
                </form>
              </div>
            </div>
            <div style={{ flex: "1 1 200px" }}>
              <table className="t">
                <tbody>
                  <tr><td>Scans</td><td><strong>{s?.scans ?? 0}</strong></td></tr>
                  <tr><td>Unique scanners*</td><td><strong>{s?.unique_scanners ?? 0}</strong></td></tr>
                  <tr><td>Students started</td><td><strong>{s?.students_started ?? 0}</strong></td></tr>
                  <tr><td>Students finished</td><td><strong>{s?.students_finished ?? 0}</strong></td></tr>
                </tbody>
              </table>
            </div>
          </div>
        </div>
      ))}
      <p className="muted">
        *Estimated from an anonymous browser cookie. A scan is counted when the page opens in a real browser; the same browser reopening the link within 10 minutes counts once.
      </p>
    </>
  );
}
